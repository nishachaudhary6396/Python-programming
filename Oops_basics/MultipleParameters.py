class human:
    def __init__(self,name,age,city,college):
        self.name = name
        self.age = age
        self.city = city
        self.college = college

h1 = human("Nisha",22,"Agra","Gla")
h2 = human("Mehak",21,"Bareli","Gla")
h3 = human("Madhu",22,"Tundla","Gla")

print(h1.name,h1.age,h1.city,h1.college)
print(h2.name,h2.age,h2.city,h2.college)
print(h3.name,h3.age,h3.city,h3.college)
